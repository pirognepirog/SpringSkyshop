                // то есть добавление, поиск, обновление и удаление сущностей, которыми управляет репозиторий.
                // Обычно репозитории работают с базой данных, но бывают и случаи, когда сущности хранятся в
                // коллекции.

// @Controller - Данной аннотацией помечаются классы-контроллеры, которые возвращают пользователю веб-страницу
                // или HTML-строку. В современной разработке практически не используется, так как большинство
                // современных Spring-приложений перешли на коммуникацию друг с другом через JSON/XML

// @RestController - Эта аннотация отмечает классы-контроллеры, которые возвращают пользователю (или приложению)
