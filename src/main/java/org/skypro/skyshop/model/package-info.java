                // в отдельный класс и разметить его аннотацией @Component

// @Service и @Component равны, но @Service помечаются классы, которые выполняют бизнес-логику.

// @Service - Сервисы содержат набор полей, которые нужны для выполнения логики.
                // Полями могут быть как другие сервисы, так и независимые компоненты вроде клиента.
                // Задача сервиса — получить запрос от контроллера с пришедшими в него параметрами,
                // провести вычисления, нужные для выполнения задачи, и вернуть результат.

// @Repository - Данной аннотацией помечаются классы-хранилища неких данных.
